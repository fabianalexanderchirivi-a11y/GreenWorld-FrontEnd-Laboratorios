import {credentials} from '../../support/ppi'
describe('TC-EDU-E2E-01 — Aprendizaje, reseña y certificado reales',()=>{
 it('persiste módulos y emite PDF solo después de completar el curso',()=>{
  cy.env(['LEARNING_COURSE_ID'],{log:false}).then(({LEARNING_COURSE_ID:id})=>{
   credentials().then(({correo,contrasena})=>{
    cy.visit('/login')
    cy.get('input[name=correo]').type(correo,{log:false})
    cy.get('input[type=password]').type(contrasena,{log:false})
    cy.contains('button','Iniciar sesión').click()
    cy.url().should('include','panel-usuario')
    cy.screenshot('TC-EDU-E2E-01-panel')
    cy.visit(`/cursos/${id}`)
    cy.contains('button','Comenzar').click()
    cy.contains('.course-state-pill','En progreso').should('be.visible')
    cy.contains('button','Terminar curso').should('be.disabled')
    cy.get('#learning-content').scrollIntoView()
    cy.contains('h3','Separar residuos').should('be.visible')
    cy.screenshot('TC-EDU-E2E-01-modulos-inicio')
    cy.contains('button','Marcar módulo como completado').click()
    cy.get('.course-progress-header strong').should('have.text','50%')
    cy.reload()
    cy.get('.course-progress-header strong').should('have.text','50%')
    cy.contains('.learning-navigation button','Cuidar el agua').click()
    cy.contains('h3','Cuidar el agua').should('be.visible')
    cy.contains('button','Marcar módulo como completado').click()
    cy.get('.course-progress-header strong').should('have.text','100%')
    cy.contains('.course-state-pill','Terminado').should('be.visible')
    cy.screenshot('TC-EDU-E2E-01-terminado')
    cy.get('#review-content').type('Reseña de prueba E2E: contenidos de educación ambiental claros.')
    cy.contains('button','Guardar mi reseña').click()
    cy.contains('[role=status]','Tu reseña quedó guardada.').should('be.visible')
    cy.contains('.review-entry','Reseña de prueba E2E').should('be.visible')
    cy.screenshot('TC-EDU-E2E-01-resena')
    cy.intercept('POST',`/api/cursos/${id}/certificado`).as('issue')
    cy.contains('button','Descargar certificado').click()
    cy.wait('@issue').then(({response})=>{
      expect(response.statusCode).to.be.oneOf([200,201])
      cy.readFile(`${Cypress.config('downloadsFolder')}/greenworld-certificado-${response.body.data.id_certificado}.pdf`,'binary').should('match',/^%PDF-/)
    })
   })
  })
 })
})
